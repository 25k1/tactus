    pub fn id(self) -> Id {
        COMMAND_BASE + Self::ALL.iter().position(|command| *command == self).unwrap_or_default() as Id
    }

    pub fn from_global(action: GlobalAction) -> Command {
        match action {
            GlobalAction::PlayPause => Command::PlayPause,
            GlobalAction::Stop => Command::Stop,
            GlobalAction::Next => Command::Next,
            GlobalAction::Previous => Command::Previous,
            GlobalAction::SeekForward => Command::SeekForward,
            GlobalAction::SeekBack => Command::SeekBack,
            GlobalAction::VolumeUp => Command::VolumeUp,
            GlobalAction::VolumeDown => Command::VolumeDown,
            GlobalAction::Like => Command::Like,
            GlobalAction::Dislike => Command::Dislike,
            GlobalAction::Wave => Command::Wave,
            GlobalAction::NowPlaying => Command::SpeakNowPlaying,
            GlobalAction::ShowWindow => Command::ToggleWindow,
            GlobalAction::Voice => Command::Listen,
        }
    }

