#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Place {
    Search,
    Wave,
    ForYou,
    Collection,
    Playlists,
    Radio,
    Podcasts,
    History,
    Queue,
    Lyrics,
    Downloads,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum NameKind {
    Any,
    Artist,
    Album,
    Playlist,
    Track,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Mood {
    Calm,
    Energetic,
    Fun,
    Sad,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum SleepRequest {
    Minutes(u32),
    EndOfTrack,
    Off,
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub enum Intent {
    Play,
    Pause,
    Stop,
    Next,
    Previous,
    VolumeUp,
    VolumeDown,
    Volume(u8),
    Faster,
    Slower,
    NormalSpeed,
    Forward(u32),
    Rewind(u32),
    RepeatOff,
    RepeatOne,
    RepeatAll,
    ShuffleOn,
    ShuffleOff,
    Sleep(SleepRequest),
    WhatsPlaying,
    PlayName { kind: NameKind, name: String },
    PlayLikes,
    PlayWave,
    PlayMood(Mood),
    Like,
    Unlike,
    Dislike,
    AddToPlaylist(String),
    Download,
    GoToAlbum,
    GoToArtist,
    Open(Place),
    Search(String),
    ReadSelection,
    GoBack,
    Help,
    Yes,
    No,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Slot {
    Nothing,
    Number,
    Name,
}

