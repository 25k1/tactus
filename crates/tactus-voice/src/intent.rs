pub fn slot(id: &str) -> Option<Slot> {
    IDS.iter().find(|(known, _)| *known == id).map(|(_, slot)| *slot)
}

pub fn build(id: &str, number: Option<u32>, name: Option<String>) -> Option<Intent> {
    let named = |kind| Some(Intent::PlayName { kind, name: name.clone()? });
    Some(match id {
        "play" => Intent::Play,
        "pause" => Intent::Pause,
        "stop" => Intent::Stop,
        "next" => Intent::Next,
        "previous" => Intent::Previous,
        "volume-up" => Intent::VolumeUp,
        "volume-down" => Intent::VolumeDown,
        "volume" => Intent::Volume(u8::try_from(number?).ok().filter(|volume| *volume <= 100)?),
        "faster" => Intent::Faster,
        "slower" => Intent::Slower,
        "normal-speed" => Intent::NormalSpeed,
        "forward" => Intent::Forward(number?.clamp(1, 3600)),
        "rewind" => Intent::Rewind(number?.clamp(1, 3600)),
        "repeat-off" => Intent::RepeatOff,
        "repeat-one" => Intent::RepeatOne,
        "repeat-all" => Intent::RepeatAll,
        "shuffle-on" => Intent::ShuffleOn,
        "shuffle-off" => Intent::ShuffleOff,
        "sleep-minutes" => Intent::Sleep(SleepRequest::Minutes(number.filter(|minutes| (1..=1440).contains(minutes))?)),
        "sleep-end-of-track" => Intent::Sleep(SleepRequest::EndOfTrack),
        "sleep-off" => Intent::Sleep(SleepRequest::Off),
        "whats-playing" => Intent::WhatsPlaying,
        "play-name" => return named(NameKind::Any),
        "play-artist" => return named(NameKind::Artist),
        "play-album" => return named(NameKind::Album),
        "play-playlist" => return named(NameKind::Playlist),
        "play-track" => return named(NameKind::Track),
        "play-likes" => Intent::PlayLikes,
        "play-wave" => Intent::PlayWave,
        "play-calm" => Intent::PlayMood(Mood::Calm),
        "play-energetic" => Intent::PlayMood(Mood::Energetic),
        "play-fun" => Intent::PlayMood(Mood::Fun),
        "play-sad" => Intent::PlayMood(Mood::Sad),
        "like" => Intent::Like,
        "unlike" => Intent::Unlike,
        "dislike" => Intent::Dislike,
        "add-to-playlist" => Intent::AddToPlaylist(name?),
        "download" => Intent::Download,
        "go-to-album" => Intent::GoToAlbum,
        "go-to-artist" => Intent::GoToArtist,
        "open-search" => Intent::Open(Place::Search),
        "open-wave" => Intent::Open(Place::Wave),
        "open-for-you" => Intent::Open(Place::ForYou),
        "open-collection" => Intent::Open(Place::Collection),
        "open-playlists" => Intent::Open(Place::Playlists),
        "open-radio" => Intent::Open(Place::Radio),
        "open-podcasts" => Intent::Open(Place::Podcasts),
        "open-history" => Intent::Open(Place::History),
        "open-queue" => Intent::Open(Place::Queue),
        "open-lyrics" => Intent::Open(Place::Lyrics),
        "open-downloads" => Intent::Open(Place::Downloads),
        "search" => Intent::Search(name?),
        "read-selection" => Intent::ReadSelection,
        "go-back" => Intent::GoBack,
        "help" => Intent::Help,
        "yes" => Intent::Yes,
        "no" => Intent::No,
        _ => return None,
    })
}
